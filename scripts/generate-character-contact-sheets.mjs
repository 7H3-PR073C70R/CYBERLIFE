#!/usr/bin/env node
/**
 * scripts/generate-character-contact-sheets.mjs
 *
 * Automated Day & Night contact sheet generator for Stage B Character Roster Upgrade.
 *
 * Saves into docs/characters/contact-sheets/stageB/:
 * - named_npcs_day.png & named_npcs_night.png
 * - pedestrian_roles_day.png & pedestrian_roles_night.png
 * - crowd_40_day.png & crowd_40_night.png
 * - realistic_comparison_day.png & realistic_comparison_night.png
 */

import { spawn } from 'child_process';
import path from 'path';
import fs from 'fs';
import puppeteer from 'puppeteer-core';

const ROOT_DIR = process.cwd();
const OUT_DIR = path.join(ROOT_DIR, 'docs', 'characters', 'contact-sheets', 'stageB');
const CHROME_PATH = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const PORT = 5173;

fs.mkdirSync(OUT_DIR, { recursive: true });

async function wait(ms) {
  return new Promise(r => setTimeout(r, ms));
}

async function isServerRunning() {
  try {
    const res = await fetch(`http://127.0.0.1:${PORT}/`);
    return res.ok;
  } catch {
    return false;
  }
}

const CAPTURE_TARGETS = [
  {
    name: 'named_npcs_day',
    subview: 'named_npcs',
    lighting: 'day',
    waitMs: 9000,
    desc: 'Lineup of all 15 Named NPCs alongside Realistic Reference Models (Midday Sun)',
  },
  {
    name: 'named_npcs_night',
    subview: 'named_npcs',
    lighting: 'night',
    waitMs: 6000,
    desc: 'Lineup of all 15 Named NPCs alongside Realistic Reference Models (Cyber Night)',
  },
  {
    name: 'pedestrian_roles_day',
    subview: 'pedestrian_roles',
    lighting: 'day',
    waitMs: 9000,
    desc: 'Pedestrian Role Roster across 22+ Authentic Lagos Island Occupations (Day)',
  },
  {
    name: 'pedestrian_roles_night',
    subview: 'pedestrian_roles',
    lighting: 'night',
    waitMs: 6000,
    desc: 'Pedestrian Role Roster across 22+ Authentic Lagos Island Occupations (Night)',
  },
  {
    name: 'crowd_40_day',
    subview: 'crowd_40',
    lighting: 'day',
    waitMs: 9000,
    desc: '40-Person Living Crowd Generated by Seeded Variation Engine (Plaza Day)',
  },
  {
    name: 'crowd_40_night',
    subview: 'crowd_40',
    lighting: 'night',
    waitMs: 6000,
    desc: '40-Person Living Crowd Generated by Seeded Variation Engine (Plaza Night)',
  },
  {
    name: 'realistic_comparison_day',
    subview: 'comparison',
    lighting: 'day',
    waitMs: 7000,
    desc: 'Close-Up Side-by-Side Cohesion: Modular Leads vs Realistic Characters (Day)',
  },
  {
    name: 'realistic_comparison_night',
    subview: 'comparison',
    lighting: 'night',
    waitMs: 6000,
    desc: 'Close-Up Side-by-Side Cohesion: Modular Leads vs Realistic Characters (Night)',
  },
];

async function main() {
  console.log('=== GENERATING STAGE B CHARACTER CONTACT SHEETS ===');

  let viteProcess = null;
  const running = await isServerRunning();

  if (!running) {
    console.log(`Starting Vite server on port ${PORT}...`);
    viteProcess = spawn('npx', ['vite', '--port', String(PORT)], {
      cwd: ROOT_DIR,
      stdio: 'pipe',
      shell: true,
    });

    let up = false;
    for (let i = 0; i < 40; i++) {
      await wait(500);
      if (await isServerRunning()) {
        up = true;
        break;
      }
    }
    if (!up) {
      console.error('Failed to start Vite server.');
      if (viteProcess) viteProcess.kill('SIGKILL');
      process.exit(1);
    }
    console.log('Vite server running.');
  } else {
    console.log('Vite server already running.');
  }

  console.log('Launching headless Chrome...');
  const browser = await puppeteer.launch({
    executablePath: CHROME_PATH,
    headless: 'new',
    args: [
      '--no-sandbox',
      '--disable-setuid-sandbox',
      '--disable-gpu-watchdog',
      '--window-size=2560,1440',
    ],
  });

  const page = await browser.newPage();
  await page.setViewport({ width: 2560, height: 1440, deviceScaleFactor: 1 });

  for (const target of CAPTURE_TARGETS) {
    const url = `http://127.0.0.1:${PORT}/?view=asset-viewer&mode=characters&subview=${target.subview}&lighting=${target.lighting}`;
    console.log(`\nNavigating to: ${target.name} [${url}]`);
    console.log(`Description: ${target.desc}`);

    await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 30000 });
    console.log(`Waiting ${target.waitMs / 1000}s for 3D meshes and textures...`);
    await wait(target.waitMs);

    const outPath = path.join(OUT_DIR, `${target.name}.png`);
    await page.screenshot({ path: outPath, fullPage: false });
    const sizeKB = (fs.statSync(outPath).size / 1024).toFixed(1);
    console.log(`Saved: ${outPath} (${sizeKB} KB)`);
  }

  await browser.close();

  if (viteProcess) {
    console.log('Stopping spawned Vite server...');
    viteProcess.kill('SIGKILL');
  }

  console.log('\n=== ALL 8 STAGE B CONTACT SHEETS SUCCESSFULLY GENERATED ===');
}

main().catch(err => {
  console.error('Fatal error during contact sheet capture:', err);
  process.exit(1);
});
