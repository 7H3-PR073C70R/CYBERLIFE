/**
 * Returns filtered threat articles tailored to the current simulation state,
 * creating an authentic illusion of dynamic news progression day by day.
 */
export function getArticlesForState(state?: SimulationState | null): ThreatNewsArticle[] {
  if (!state) {
    return ALL_THREAT_ARTICLES.filter(a => !a.requiredFlag && !a.minDay);
  }

  // Simulation begins on Oct 12, 2026 (Day 1)
  const simDay = Math.max(1, state.time.calendar.day - 11);
  const flags = state.flags;

  return ALL_THREAT_ARTICLES.filter(article => {
    // Check day requirement
    if (article.minDay && simDay < article.minDay) {
      return false;
    }

    // Check flag requirement
    if (article.requiredFlag && !flags[article.requiredFlag]) {
      return false;
    }

    return true;
  });
}
